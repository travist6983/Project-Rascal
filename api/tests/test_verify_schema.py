"""The deploy-time schema check must expect the same things the migration test does.

`.github/scripts/verify_schema.py` runs against Neon; `test_migrations.py` runs against a
throwaway local database. They assert the same named objects. Nothing keeps two hand-written
lists in step except a test that compares them — without this, an index added to the
migration and to `test_migrations.py` would silently go unverified on the real database,
which is the one place it matters.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

import test_migrations

SCRIPT = Path(__file__).resolve().parents[2] / ".github" / "scripts" / "verify_schema.py"


@pytest.fixture(scope="module")
def verify():
    spec = importlib.util.spec_from_file_location("verify_schema", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.mark.parametrize(
    "attribute",
    [
        "EXPECTED_TABLES",
        "EXPECTED_INDEXES",
        "EXPECTED_CHECKS",
        "TABLES_WITH_UPDATED_AT_TRIGGER",
    ],
)
def test_the_two_expectation_lists_agree(verify, attribute: str) -> None:
    assert getattr(verify, attribute) == getattr(test_migrations, attribute), (
        f"{attribute} differs between .github/scripts/verify_schema.py and "
        f"tests/test_migrations.py — update both."
    )


def test_the_generated_columns_are_the_ones_the_models_declare(verify) -> None:
    """Search silently returns nothing if these are not actually generated by Postgres."""
    checked = verify.GENERATED_COLUMNS
    assert checked == {("entries", "search_vector"), ("media", "search_vector")}
